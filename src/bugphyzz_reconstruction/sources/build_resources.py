"""
Build internal Bugphyzz Python resource files.

This is the Python equivalent of the R sysdata.Rda build script.
It generates:

    resources/taxonomy_2023/ranks_parents.tsv
    resources/bacdive_phys_names.txresourcest

These files should be generated by the package developer and shipped with the
Python package. End users should not need to run this script.

Requirements
------------
- pandas
- ete3, with the NCBI taxonomy database initialized
- local translated modules: physiologies.py and bacdive.py

Example
-------
python scripts/build_resources.py --resource-dir resources

Notes
-----
The original R script used taxizedb::classification(), taxid2rank(), and
 taxid2name(). This Python version uses ete3.NCBITaxa for equivalent local NCBI
 taxonomy lookups.
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path
from typing import Iterable, Optional

import pandas as pd

try:
    from ete3 import NCBITaxa
except ImportError as exc:  # pragma: no cover
    raise ImportError(
        "build_resources.py requires ete3. Install it with `pip install ete3`."
    ) from exc

from bugphyzz_reconstruction.sources.physiologies import physiologies
from bugphyzz_reconstruction.sources.bacdive import get_bacdive, reshape_bacdive


LOWEST_RANKS = {
    "biotype",
    "isolate",
    "serogroup",
    "serotype",
    "strain",
    "subspecies",
}

TAX_RANKS = [
    "superkingdom",
    "phylum",
    "class",
    "order",
    "family",
    "genus",
    "species",
    "strain",
]


def get_parent_rank(rank: Optional[str]) -> Optional[str]:
    """
    Direct Python equivalent of getParentRank() from the R build script.
    """
    if rank in LOWEST_RANKS:
        return "species"
    if rank == "species":
        return "genus"
    if rank == "genus":
        return "family"
    return None


def clean_ncbi_ids(ids: Iterable[object]) -> list[str]:
    """
    Match the R cleaning behavior:
    - squish whitespace
    - lowercase strings
    - drop unknown and missing values
    - unique
    - sort decreasing
    """
    cleaned: set[str] = set()

    for value in ids:
        if pd.isna(value):
            continue
        taxid = " ".join(str(value).strip().split()).lower()
        if not taxid or taxid == "unknown" or taxid == "nan":
            continue
        cleaned.add(taxid)

    return sorted(cleaned, reverse=True)


def collect_ncbi_ids(resource_dir: Path) -> list[str]:
    """
    Collect NCBI IDs without calling physiologies().

    This avoids a circular dependency:
    physiologies() needs ranks_parents.tsv,
    but this builder creates ranks_parents.tsv.
    """
    resource_dir = Path(resource_dir)
    ids: set[str] = set()

    # Collect IDs from spreadsheet-linked datasets
    links_path = resource_dir / "spreadsheet_links.tsv"
    links = pd.read_csv(links_path, sep="\t")

    for url in links["link"].dropna().unique():
        df = pd.read_csv(url)

        if "NCBI_ID" not in df.columns:
            continue

        values = (
            df["NCBI_ID"]
            .astype(str)
            .str.strip()
            .str.lower()
        )

        values = values[
            values.notna()
            & (values != "")
            & (values != "nan")
            & (values != "unknown")
        ]

        ids.update(values.tolist())

    # Collect IDs from BacDive, if available
    try:
        bacdive = get_bacdive(verbose=False)

        if "NCBI_ID" in bacdive.columns:
            values = (
                bacdive["NCBI_ID"]
                .astype(str)
                .str.strip()
                .str.lower()
            )

            values = values[
                values.notna()
                & (values != "")
                & (values != "nan")
                & (values != "unknown")
            ]

            ids.update(values.tolist())

    except Exception as exc:
        print(f"Warning: could not collect BacDive NCBI IDs: {exc}")

    return sorted(ids, reverse=True)


def get_lineage_table(ncbi: NCBITaxa, taxid: str) -> Optional[pd.DataFrame]:
    """
    Return a taxonomy table equivalent to taxizedb::classification().

    Columns:
        id, name, rank
    """
    try:
        lineage = ncbi.get_lineage(int(taxid))
    except Exception:
        return None

    if not lineage:
        return None

    ranks = ncbi.get_rank(lineage)
    names = ncbi.get_taxid_translator(lineage)

    table = pd.DataFrame(
        {
            "id": [str(x) for x in lineage],
            "name": [names.get(x, pd.NA) for x in lineage],
            "rank": [ranks.get(x, pd.NA) for x in lineage],
        }
    )
    return table


def find_parent_id_for_rank(
    lineage_table: pd.DataFrame,
    expected_parent_rank: str,
) -> Optional[str]:
    """
    Match the R parent selection logic:
    - keep only taxRanks
    - remove the current rank / terminal row
    - take the last remaining parent
    - keep it only if its rank matches expected_parent_rank
    """
    ranked = lineage_table[lineage_table["rank"].isin(TAX_RANKS)].copy()

    if len(ranked) <= 1:
        return None

    ranked = ranked.iloc[:-1]
    parent = ranked.tail(1)

    if parent.empty:
        return None

    parent_rank = parent["rank"].iloc[0]
    parent_id = parent["id"].iloc[0]

    if parent_rank == expected_parent_rank:
        return str(parent_id)

    return None


def build_ranks_parents(resource_dir: Path) -> pd.DataFrame:
    """
    Build the Python replacement for the internal R ranksParents object.
    """
    start = time.time()
    ncbi = NCBITaxa()

    ncbi_ids = collect_ncbi_ids(resource_dir=resource_dir)
    print(f"Collected {len(ncbi_ids):,} unique NCBI IDs from physiologies().")

    rows: list[dict[str, object]] = []
    failed = 0
    skipped_no_parent_rank = 0
    skipped_no_parent_id = 0

    for taxid in ncbi_ids:
        lineage_table = get_lineage_table(ncbi, taxid)
        if lineage_table is None or lineage_table.empty:
            failed += 1
            continue

        current_rank = lineage_table["rank"].iloc[-1]
        expected_parent_rank = get_parent_rank(current_rank)

        if expected_parent_rank is None:
            skipped_no_parent_rank += 1
            continue

        parent_id = find_parent_id_for_rank(lineage_table, expected_parent_rank)
        if parent_id is None:
            skipped_no_parent_id += 1
            continue

        try:
            current_name = ncbi.get_taxid_translator([int(taxid)]).get(int(taxid), pd.NA)
            parent_name = ncbi.get_taxid_translator([int(parent_id)]).get(int(parent_id), pd.NA)
            parent_rank = ncbi.get_rank([int(parent_id)]).get(int(parent_id), pd.NA)
        except Exception:
            failed += 1
            continue

        rows.append(
            {
                "NCBI_ID": str(taxid),
                "Taxon_name": current_name,
                "Rank": current_rank,
                "Parent_NCBI_ID": str(parent_id),
                "Parent_name": parent_name,
                "Parent_rank": parent_rank,
            }
        )

    out = pd.DataFrame(
        rows,
        columns=[
            "NCBI_ID",
            "Taxon_name",
            "Rank",
            "Parent_NCBI_ID",
            "Parent_name",
            "Parent_rank",
        ],
    )

    elapsed = time.time() - start
    print(f"Built ranks_parents table with {len(out):,} rows in {elapsed:.1f}s.")
    print(f"Failed taxonomy lookups: {failed:,}")
    print(f"Skipped because rank has no parent-rank rule: {skipped_no_parent_rank:,}")
    print(f"Skipped because expected parent ID was not found: {skipped_no_parent_id:,}")

    return out


def build_bacdive_phys_names() -> list[str]:
    """
    Build the Python replacement for the internal R bacdivePhysNames vector.
    """
    bacdive = reshape_bacdive(get_bacdive(verbose=False))
    return sorted(bacdive.keys())


def write_ranks_parents(df: pd.DataFrame, resource_dir: Path) -> Path:
    resource_dir.mkdir(parents=True, exist_ok=True)
    out_path = resource_dir / "ranks_parents.tsv"
    df.to_csv(out_path, sep="\t", index=False)
    return out_path


def write_bacdive_phys_names(names: list[str], resource_dir: Path) -> Path:
    resource_dir.mkdir(parents=True, exist_ok=True)
    out_path = resource_dir / "bacdive_phys_names.txt"
    out_path.write_text("\n".join(names) + "\n", encoding="utf-8")
    return out_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate Bugphyzz Python resource files."
    )
    parser.add_argument(
        "--resource-dir",
        default="C:/Users/delan/OneDrive/Desktop/bugphyzz_reconstruction/src/bugphyzz_reconstruction/resources/taxonomy_2023",
        type=Path,
        help="Directory containing Bugphyzz resource files and where outputs are written.",
    )
    parser.add_argument(
        "--skip-ranks-parents",
        action="store_true",
        help="Only build bacdive_phys_names.txt.",
    )
    parser.add_argument(
        "--skip-bacdive-phys-names",
        action="store_true",
        help="Only build ranks_parents.tsv.",
    )
    args = parser.parse_args()

    resource_dir = args.resource_dir

    if not args.skip_ranks_parents:
        ranks_parents = build_ranks_parents(resource_dir=resource_dir)
        ranks_path = write_ranks_parents(ranks_parents, resource_dir=resource_dir)
        print(f"Wrote {ranks_path}")

    if not args.skip_bacdive_phys_names:
        bacdive_phys_names = build_bacdive_phys_names()
        names_path = write_bacdive_phys_names(bacdive_phys_names, resource_dir=resource_dir)
        print(f"Wrote {names_path}")


if __name__ == "__main__":
    main()
